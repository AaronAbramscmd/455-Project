    <p><strong>Does it hurt when you get hit?</strong></p>
    <p>Paintball hit can be described more as a sting, similar to having a rubber band snapped against your arm.</p>

    <p><strong>Is there a minimum age requirement to play?</strong></p>
    <p>Yes, for walk-on play, which is .68 caliber, the minimum age is 10 years old.<br>
    For low impact parties, the minimum age is 8 years old.<br>
    For gel ball parties, the minimum age is 6 years old.</p>

    <p><strong>How much paint will I shoot in a day?</strong></p>
    <p>The average player will shoot 500-1,000 paintballs per day. It all depends on how you shoot.</p>

    <p><strong>Do we need a whole team to play?</strong></p>
    <p>No, walk-on players (individuals) are welcome every Saturday &amp; Sunday from 10:00am to 5:00pm.<br>
    All walk-on players are joined together to play.</p>

    <p><strong>What method of payments do you accept?</strong></p>
    <p>Cash, Credit Card, Apple Pay</p>

    <p><strong>Do you have bathrooms?</strong></p>
    <p>We have porta-potties! There is no running water at the paintball field.</p>

    <p><strong>Can we play by ourselves?</strong></p>
    <p>Yes, with a group of 15 or more players and a reservation you can have a private game with a referee.<br>
    You must make a reservation and leave a $100 deposit.<br>
    There is no extra charge for private games.</p>

    <p><strong>Are you open during the week?</strong></p>
    <p>We are open during the week by reservation of 15 or more players.</p>

    <p><strong>What clothing should we wear?</strong></p>
    <p>We recommend old clothes, something you don't mind getting dirty.<br>
    Paintballs do wash out, but sometimes they leave little oil stains on clothing.<br>
    Closed-toed shoes are a MUST. We do NOT allow anyone to play in flip-flops, Crocs, heels, or any other open-toed shoes.<br>
    Many players will wear layers, so they can take some layers off to cool down or before getting in the car.</p>

    <p><strong>What safety equipment do I need?</strong></p>
    <p>Many players will wear a hoodie and pull the hood up to protect their head.<br>
    Some players wear elbow and knee pads.<br>
    Paintball masks are a necessity. If you don't feel comfortable wearing one of ours, you can bring your own, or purchase one from our pro shop down the road.</p>

    <p><strong>Do you play in the rain?</strong></p>
    <p>Yes, we play Paintball rain or shine.<br>
    We do allow, and encourage players to bring pop-up canopies.<br>
    AIRSOFT can NOT play in the rain, due to the guns being electric.</p>

    <p><strong>Is there somewhere for parents to sit during a birthday party?</strong></p>
    <p>Yes, we have a staging area with over 40 tables, chairs are limited at this time.<br>
    Parents are welcome to stay and hang out.<br>
    We do allow and encourage customers to bring pop-up tents as well as folding chairs.</p>

    <p><strong>Can we bring food and drinks?</strong></p>
    <p>Absolutely! You can bring food and drinks.<br>
    There is no refrigeration or freezers to store cupcakes or cakes.<br>
    We do NOT allow alcohol! Paintball and Alcohol don't mix very well.<br>
    Many pizzerias will also deliver.</p>

    <p><strong>Can we bring a birthday cake and decorations for my child's birthday party?</strong></p>
    <p>YES! You are welcome to bring cake, food and/or drinks.<br>
    NO ALCOHOL.<br>
    Tablecloths, balloons, and decorations are also allowed.<br>
    We do ask you clean up and dispose of all decorations at the end of the party.<br>
    Don't forget plates, forks, and cups! Also a knife to cut the cake!<br>
    There is no refrigeration or freezers to store cupcakes or cakes.</p>

    <p><strong>What if we book a birthday party package #2 and only 8 kids show up?</strong></p>
    <p>This is the most asked question.<br>
    We do NOT hold you to the package you book.<br>
    If only 8 kids show up, then we would move you to a package #1.<br>
    If more kids show up we will move you up a package.</p>

    <p><strong>Do players need to wear chest protectors?</strong></p>
    <p>It is NOT a requirement for a player to wear a chest protector.<br>
    The only required piece of equipment is a paintball mask and barrel sock.</p>

    <p><strong>We have a 12:00pm reservation, what time should we arrive?</strong></p>
    <p>A party reservation is just like a tee time or dinner reservation.<br>
    Example: If booked at 4pm please arrive at 4pm.<br>
    You won't be eating at that time but your table will be ready for you to check in!<br>
    You may arrive early but it's not totally necessary.</p>

    <p><strong>If we have a 10:30-2:30 birthday party, can the kids play with walk-ons when the party is over?</strong></p>
    <p>Great Question! Birthday parties are a 3-4 hour package deal.<br>
    Players can join walk-on play, but would need to sign in and pay the full walk-on rate.</p>

    <p><strong>Do we go directly to the field or the pro shop?</strong></p>
    <p>Everything is done at the paintball field.<br>
    You can, however, stop at our pro shop for any of your paintball needs.</p>

    <p><strong>What is the address for the field?</strong></p>
    <p>162 O'Haire Road, Middletown, NY 10941<br>
    Follow the long gravel road into our parking lot.</p>

    <p><strong>I can't find the online waiver I need to sign?</strong></p>
    <p>The party host will receive a link for the online waiver.<br>
    The waiver link can be sent via email, text message, or even in a Facebook event page.<br>
    The online waiver link is for private parties only.<br>
    It cannot be used for walk-on play.</p>
